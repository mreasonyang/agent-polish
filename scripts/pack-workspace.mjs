import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { withLock } from './installer_lock.mjs';

const root = fs.realpathSync(fileURLToPath(new URL('..', import.meta.url)));
const workspace = fs.realpathSync(process.cwd());
const name = basename(workspace);
const marker = '.npm-pack-assets';
const nativeMetadata = new Set(['.codex-plugin', '.antigravity-plugin']);
const ignored = new Set(['node_modules', 'Thumbs.db', 'desktop.ini']);
const readJSON = path => JSON.parse(fs.readFileSync(path, 'utf8'));

function copyAsset(source, target) {
  const entry = fs.lstatSync(source);
  if (entry.isDirectory()) {
    fs.mkdirSync(target, { recursive: true });
    for (const child of fs.readdirSync(source)) {
      if (ignored.has(child) || (child.startsWith('.') && !nativeMetadata.has(child))) continue;
      copyAsset(join(source, child), join(target, child));
    }
  } else if (entry.isFile()) {
    fs.mkdirSync(dirname(target), { recursive: true });
    fs.copyFileSync(source, target, fs.constants.COPYFILE_EXCL);
  } else {
    throw new Error(`Cannot pack a symlink or special file at ${source}`);
  }
}

function fingerprint(directory) {
  const hash = createHash('sha256');
  function visit(relative) {
    const path = join(directory, relative);
    const entry = fs.lstatSync(path);
    if (entry.isDirectory()) {
      hash.update(`directory\0${relative}\0`);
      for (const child of fs.readdirSync(path).sort()) {
        if (!relative && child === marker) continue;
        visit(join(relative, child));
      }
    } else if (entry.isFile()) {
      hash.update(`file\0${relative}\0${entry.mode & 0o111}\0`);
      hash.update(createHash('sha256').update(fs.readFileSync(path)).digest());
    } else {
      throw new Error(`Unexpected file type at ${path}`);
    }
  }
  visit('');
  return hash.digest('hex');
}

function outputChange(staging, directory) {
  const target = join(workspace, directory);
  const incoming = join(staging, directory);
  const next = fingerprint(incoming);
  const current = fs.lstatSync(target, { throwIfNoEntry: false });
  if (current) {
    const stamp = join(target, marker);
    if (!current.isDirectory() || !fs.lstatSync(stamp, { throwIfNoEntry: false })?.isFile()) {
      throw new Error(`Cannot replace existing workspace files at ${target}`);
    }
    const previous = fingerprint(target);
    if (fs.readFileSync(stamp, 'utf8') !== `${previous}\n`) {
      throw new Error(`Cannot replace modified workspace files at ${target}`);
    }
    if (next === previous) return null;
  }
  fs.writeFileSync(join(incoming, marker), `${next}\n`, { flag: 'wx' });
  return { target, incoming, backup: current && join(staging, 'previous', directory) };
}

function stage(files, bin) {
  const staging = fs.mkdtempSync(join(workspace, '.npm-pack-'));
  let recoveryNeeded = false;
  try {
    for (const file of files) copyAsset(join(root, file), join(staging, file));
    const entry = join(staging, bin);
    if (!fs.readFileSync(entry, 'utf8').startsWith('#!/usr/bin/env node\n')) {
      throw new Error(`Expected a Node CLI entry point at ${bin}`);
    }
    fs.chmodSync(entry, 0o755);

    // Each generated tree owns its contents. Compare the last generated bytes
    // before replacing anything, so local files and edits are preserved.
    const directories = new Set(files.map(file => file.split('/')[0]));
    const changes = [...directories].map(directory => outputChange(staging, directory)).filter(Boolean);
    for (const { target, incoming, backup } of changes) {
      if (backup) {
        fs.mkdirSync(dirname(backup), { recursive: true });
        fs.renameSync(target, backup);
      }
      try {
        fs.renameSync(incoming, target);
      } catch (error) {
        if (backup) {
          recoveryNeeded = true;
          fs.renameSync(backup, target);
          recoveryNeeded = false;
        }
        throw error;
      }
    }
  } finally {
    if (!recoveryNeeded) fs.rmSync(staging, { force: true, recursive: true });
  }
}

const manifestName = {
  'codex-polish': '.codex-plugin/plugin.json',
  'agy-polish': 'plugin.json'
}[name];
if (!manifestName || workspace !== join(root, 'packages', name)) {
  throw new Error('Run prepack from an agent-polish workspace');
}
const pkg = readJSON(join(workspace, 'package.json'));
const native = readJSON(join(root, 'plugins', name, manifestName));
if (pkg.name !== `@kyun.si/${name}` || native.name !== name || native.version !== pkg.version) {
  throw new Error(`The package and native plugin names or versions disagree for ${name}`);
}
const bin = pkg.bin[name];
// Finder launchers are maintained directly in the Codex workspace for macOS.
const launchers = name === 'codex-polish' ? ['Install Codex Polish.command', '安装回复润色.command'] : [];
for (const file of launchers) {
  if (!pkg.files.includes(file) || !fs.lstatSync(join(workspace, file)).isFile()) {
    throw new Error(`Missing Finder launcher at ${file}`);
  }
}
const files = pkg.files.filter(file => !launchers.includes(file));
if (!files.includes(bin) || !files.includes(`plugins/${name}`) || !files.every(file =>
  /^(?:\.agents\/plugins\/marketplace\.json|plugins\/[a-z-]+|scripts\/[a-z0-9_-]+\.mjs)$/.test(file) &&
  (!file.startsWith('plugins/') || file === `plugins/${name}`)
)) {
  throw new Error('Expected workspace files to list plugin assets and installer scripts');
}

await withLock(workspace, () => stage(files, bin));
